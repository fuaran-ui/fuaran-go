// Package idlgen renders this host's structural layer from the corpus's
// idl.json bytes. It is the whole generator; ../gen is the command that reads
// the corpus and writes (or checks) the files, and ../../drift_test.go calls
// Generate in-process to prove the committed output is current.
//
// The output is deterministic — rows keep idl.json's order, every map is
// emitted in sorted order and the source is run through go/format — so the
// same idl.json always yields the same bytes.
package idlgen

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/fuaran-ui/fuaran-go/canonical"
)

// Output is one generated file, at a module-relative slash path.
type Output struct {
	Path    string
	Content []byte
}

// The generated files, module-relative.
const (
	IDLFile      = "wire/idl/idl_gen.go"
	KindArmsFile = "wire/kindarms_gen.go"
)

// Header is the first line of every generated file (the Go toolchain's
// "generated code" marker).
const Header = "// Code generated by go run ./wire/idl/internal/gen from the corpus idl.json; DO NOT EDIT."

// Hash is the recorded identity of an idl.json: SHA-256 over its exact bytes.
// The corpus pins its text files to LF, so the bytes are the same on every
// checkout.
func Hash(src []byte) string {
	sum := sha256.Sum256(src)
	return hex.EncodeToString(sum[:])
}

type rawType struct {
	Type   string          `json:"$type"`
	Name   string          `json:"name"`
	Args   []*rawType      `json:"args"`
	Of     *rawType        `json:"of"`
	Values *rawType        `json:"values"`
	Wire   json.RawMessage `json:"wire"`
}

type rawOptionality struct {
	Type    string          `json:"$type"`
	Default json.RawMessage `json:"default"`
}

type rawField struct {
	Name        string         `json:"name"`
	Optionality rawOptionality `json:"optionality"`
	Type        *rawType       `json:"type"`
}

type rawKind struct {
	Tag      string     `json:"tag"`
	Category string     `json:"category"`
	Fields   []rawField `json:"fields"`
}

type rawEnum struct {
	Name      string   `json:"name"`
	Cases     []string `json:"cases"`
	HostCases []string `json:"hostCases"`
}

type rawCase struct {
	Tag         string     `json:"tag"`
	Fields      []rawField `json:"fields"`
	Annotations struct {
		InProcessOnly bool `json:"inProcessOnly"`
	} `json:"annotations"`
}

type rawUnion struct {
	Name            string    `json:"name"`
	Params          []string  `json:"params"`
	TransparentCase string    `json:"transparentCase"`
	Cases           []rawCase `json:"cases"`
}

type rawRecord struct {
	Name   string     `json:"name"`
	Fields []rawField `json:"fields"`
}

type rawIDL struct {
	Version    int         `json:"version"`
	Kinds      []rawKind   `json:"kinds"`
	Enums      []rawEnum   `json:"enums"`
	Unions     []rawUnion  `json:"unions"`
	Records    []rawRecord `json:"records"`
	Ops        []rawKind   `json:"ops"`
	NodeFields []rawField  `json:"nodeFields"`
}

var ident = regexp.MustCompile(`^[A-Z][A-Za-z0-9]*$`)

// reserved are the hand-written exported names of package idl that a
// generated row identifier must not collide with.
var reserved = map[string]bool{
	"KindTags": true, "KindByTag": true, "Kinds": true, "EnumByName": true, "Enums": true,
	"UnionByName": true, "Unions": true, "RecordByName": true, "Records": true,
	"OpByTag": true, "OpTags": true, "Ops": true, "NodeFields": true,
}

type gen struct {
	idl    rawIDL
	unions map[string]*rawUnion
	enums  map[string]bool
	err    error
}

func (g *gen) failf(format string, args ...any) {
	if g.err == nil {
		g.err = fmt.Errorf(format, args...)
	}
}

// Generate renders both generated files from idl.json's bytes.
func Generate(src []byte) ([]Output, error) {
	g := &gen{unions: map[string]*rawUnion{}, enums: map[string]bool{}}
	dec := json.NewDecoder(bytes.NewReader(src))
	if err := dec.Decode(&g.idl); err != nil {
		return nil, fmt.Errorf("idl.json does not parse: %w", err)
	}
	if len(g.idl.Kinds) == 0 || len(g.idl.Ops) == 0 {
		return nil, fmt.Errorf("idl.json declares no kinds or no ops — this is not the vocabulary file")
	}
	for i := range g.idl.Unions {
		g.unions[g.idl.Unions[i].Name] = &g.idl.Unions[i]
	}
	for _, e := range g.idl.Enums {
		g.enums[e.Name] = true
	}
	idlSrc := g.renderIDL(Hash(src))
	armsSrc := g.renderArms()
	if g.err != nil {
		return nil, g.err
	}
	var outs []Output
	for _, o := range []Output{{IDLFile, idlSrc}, {KindArmsFile, armsSrc}} {
		formatted, err := format.Source(o.Content)
		if err != nil {
			return nil, fmt.Errorf("%s: generated source does not format: %w", o.Path, err)
		}
		outs = append(outs, Output{o.Path, formatted})
	}
	return outs, nil
}

func (g *gen) identFor(prefix, name string) string {
	if !ident.MatchString(name) {
		g.failf("%s name %q is not a Go identifier fragment", prefix, name)
		return prefix + "Invalid"
	}
	id := prefix + name
	if reserved[id] {
		g.failf("%s %q collides with the hand-written identifier %s", prefix, name, id)
	}
	return id
}

var typeKinds = map[string]string{
	"str": "TStr", "bool": "TBool", "int": "TInt", "float": "TFloat", "json": "TJSON",
	"node": "TNode", "kind": "TKind", "op": "TOp", "list": "TList", "map": "TMap",
	"enum": "TEnum", "union": "TUnion", "record": "TRecord", "fn": "TFn",
	"hosted": "THosted", "var": "TVar",
}

func (g *gen) typeLit(t *rawType) string {
	if t == nil {
		g.failf("a field has no type")
		return "Type{}"
	}
	kind, ok := typeKinds[t.Type]
	if !ok {
		g.failf("unknown type shape %q — the generator must learn it before this idl.json can be projected", t.Type)
		return "Type{}"
	}
	parts := []string{"Kind: " + kind}
	if t.Name != "" {
		parts = append(parts, "Name: "+strconv.Quote(t.Name))
	}
	if len(t.Args) > 0 {
		args := make([]string, len(t.Args))
		for i, a := range t.Args {
			args[i] = g.typeLit(a)
		}
		parts = append(parts, "Args: []Type{"+strings.Join(args, ", ")+"}")
	}
	elem := t.Of
	if t.Type == "map" {
		elem = t.Values
	}
	// A carrier is either a token (the closure sentinel, "json") or, for a
	// hosted type, the wire TYPE the host value travels as.
	if len(t.Wire) > 0 {
		var token string
		if err := json.Unmarshal(t.Wire, &token); err == nil {
			parts = append(parts, "Wire: "+strconv.Quote(token))
		} else {
			var carrier rawType
			if err := json.Unmarshal(t.Wire, &carrier); err != nil {
				g.failf("a wire carrier is neither a token nor a type: %s", t.Wire)
			}
			elem = &carrier
		}
	}
	if elem != nil {
		parts = append(parts, "Elem: &"+g.typeLit(elem))
	}
	return "Type{" + strings.Join(parts, ", ") + "}"
}

var optionalities = map[string]string{
	"required": "Required", "optional": "Optional", "omitDefault": "OmitDefault", "hostOnly": "HostOnly",
}

func (g *gen) fieldsLit(fields []rawField) string {
	var sb strings.Builder
	sb.WriteString("[]Field{\n")
	for _, f := range fields {
		opt, ok := optionalities[f.Optionality.Type]
		if !ok {
			g.failf("field %q: unknown optionality %q", f.Name, f.Optionality.Type)
		}
		def := ""
		if f.Optionality.Type == "omitDefault" {
			def = g.defaultWire(f.Optionality.Default, f.Type)
		}
		fmt.Fprintf(&sb, "{Name: %s, Optionality: %s", strconv.Quote(f.Name), opt)
		if def != "" {
			fmt.Fprintf(&sb, ", Default: %s", strconv.Quote(def))
		}
		fmt.Fprintf(&sb, ", Type: %s},\n", g.typeLit(f.Type))
	}
	sb.WriteString("}")
	return sb.String()
}

type rawLiteral struct {
	Type   string            `json:"$type"`
	Value  json.RawMessage   `json:"value"`
	Case   string            `json:"case"`
	Tag    string            `json:"tag"`
	Items  []json.RawMessage `json:"items"`
	Fields []struct {
		Name  string          `json:"name"`
		Value json.RawMessage `json:"value"`
	} `json:"fields"`
}

// defaultWire renders an omit-at-default literal as the canonical wire JSON a
// conformant encoder would write for it (WIRE_FORMAT.md section 2), so a host
// compares a decoded value with its default by comparing encodings.
func (g *gen) defaultWire(raw json.RawMessage, t *rawType) string {
	var lit rawLiteral
	if err := json.Unmarshal(raw, &lit); err != nil {
		g.failf("an omit-at-default value does not parse: %v", err)
		return ""
	}
	switch lit.Type {
	case "bool":
		var b bool
		_ = json.Unmarshal(lit.Value, &b)
		return strconv.FormatBool(b)
	case "int":
		var n int64
		if err := json.Unmarshal(lit.Value, &n); err != nil {
			g.failf("an int default is not an integer: %s", lit.Value)
		}
		return strconv.FormatInt(n, 10)
	case "float":
		var f float64
		_ = json.Unmarshal(lit.Value, &f)
		return canonical.FormatFiniteDouble(f)
	case "str":
		var s string
		_ = json.Unmarshal(lit.Value, &s)
		return canonical.EscapeString(s)
	case "enum":
		return canonical.EscapeString(lit.Case)
	case "list":
		var elem *rawType
		if t != nil {
			elem = t.Of
		}
		items := make([]string, len(lit.Items))
		for i, it := range lit.Items {
			items[i] = g.defaultWire(it, elem)
		}
		return "[" + strings.Join(items, ",") + "]"
	case "union":
		u := (*rawUnion)(nil)
		if t != nil {
			u = g.unions[t.Name]
		}
		if u != nil && u.TransparentCase != "" && u.TransparentCase == lit.Tag && len(lit.Fields) == 1 {
			return g.defaultWire(lit.Fields[0].Value, nil)
		}
		members := map[string]string{"$type": canonical.EscapeString(lit.Tag)}
		for _, f := range lit.Fields {
			members[f.Name] = g.defaultWire(f.Value, nil)
		}
		return objectWire(members)
	case "record":
		members := map[string]string{}
		for _, f := range lit.Fields {
			members[f.Name] = g.defaultWire(f.Value, nil)
		}
		return objectWire(members)
	}
	g.failf("unknown default literal shape %q", lit.Type)
	return ""
}

func objectWire(members map[string]string) string {
	keys := make([]string, 0, len(members))
	for k := range members {
		keys = append(keys, k)
	}
	canonical.SortKeys(keys)
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = canonical.EscapeString(k) + ":" + members[k]
	}
	return "{" + strings.Join(parts, ",") + "}"
}

func quoteList(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = strconv.Quote(s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func (g *gen) renderIDL(hash string) []byte {
	var sb strings.Builder
	sb.WriteString(Header + "\n\n")
	sb.WriteString("package idl\n\n")
	sb.WriteString("// SourceSHA256 is the SHA-256 of the idl.json bytes this file was generated from.\n")
	fmt.Fprintf(&sb, "const SourceSHA256 = %q\n\n", hash)
	sb.WriteString("// SourceVersion is the idl.json format version.\n")
	fmt.Fprintf(&sb, "const SourceVersion = %d\n\n", g.idl.Version)

	sb.WriteString("// The NodeKind rows.\nvar (\n")
	var kindIDs []string
	for _, k := range g.idl.Kinds {
		id := g.identFor("Kind", k.Tag)
		kindIDs = append(kindIDs, "&"+id)
		fmt.Fprintf(&sb, "%s = Kind{Tag: %q, Category: %q, Fields: %s}\n", id, k.Tag, k.Category, g.fieldsLit(k.Fields))
	}
	sb.WriteString(")\n\n// The enum rows.\nvar (\n")
	var enumIDs []string
	for _, e := range g.idl.Enums {
		id := g.identFor("Enum", e.Name)
		enumIDs = append(enumIDs, "&"+id)
		fmt.Fprintf(&sb, "%s = Enum{Name: %q, Cases: %s", id, e.Name, quoteList(e.Cases))
		if len(e.HostCases) > 0 {
			fmt.Fprintf(&sb, ", HostCases: %s", quoteList(e.HostCases))
		}
		sb.WriteString("}\n")
	}
	sb.WriteString(")\n\n// The union rows.\nvar (\n")
	var unionIDs []string
	for _, u := range g.idl.Unions {
		id := g.identFor("Union", u.Name)
		unionIDs = append(unionIDs, "&"+id)
		fmt.Fprintf(&sb, "%s = Union{Name: %q", id, u.Name)
		if len(u.Params) > 0 {
			fmt.Fprintf(&sb, ", Params: %s", quoteList(u.Params))
		}
		if u.TransparentCase != "" {
			fmt.Fprintf(&sb, ", TransparentCase: %q", u.TransparentCase)
		}
		sb.WriteString(", Cases: []Case{\n")
		for _, c := range u.Cases {
			fmt.Fprintf(&sb, "{Tag: %q, Fields: %s", c.Tag, g.fieldsLit(c.Fields))
			if c.Annotations.InProcessOnly {
				sb.WriteString(", InProcessOnly: true")
			}
			sb.WriteString("},\n")
		}
		sb.WriteString("}}\n")
	}
	sb.WriteString(")\n\n// The record rows.\nvar (\n")
	var recordIDs []string
	for _, r := range g.idl.Records {
		id := g.identFor("Record", r.Name)
		recordIDs = append(recordIDs, "&"+id)
		fmt.Fprintf(&sb, "%s = Record{Name: %q, Fields: %s}\n", id, r.Name, g.fieldsLit(r.Fields))
	}
	sb.WriteString(")\n\n// The TreeOp rows.\nvar (\n")
	var opIDs []string
	for _, o := range g.idl.Ops {
		id := g.identFor("Op", o.Tag)
		opIDs = append(opIDs, "&"+id)
		fmt.Fprintf(&sb, "%s = Op{Tag: %q, Fields: %s}\n", id, o.Tag, g.fieldsLit(o.Fields))
	}
	sb.WriteString(")\n\n")
	sb.WriteString("// NodeFields is the node envelope's field table (beside id and kind).\n")
	fmt.Fprintf(&sb, "var NodeFields = %s\n\n", g.fieldsLit(g.idl.NodeFields))
	for _, set := range []struct {
		name, typ, doc string
		ids            []string
	}{
		{"Kinds", "Kind", "every NodeKind row", kindIDs},
		{"Enums", "Enum", "every enum row", enumIDs},
		{"Unions", "Union", "every union row", unionIDs},
		{"Records", "Record", "every record row", recordIDs},
		{"Ops", "Op", "every TreeOp row", opIDs},
	} {
		fmt.Fprintf(&sb, "// %s is %s, in idl.json order.\n", set.name, set.doc)
		fmt.Fprintf(&sb, "var %s = []*%s{%s}\n\n", set.name, set.typ, strings.Join(set.ids, ", "))
	}
	return []byte(sb.String())
}

// renderArms renders package wire's decoder arm set: one method per kind on an
// interface, a table-driven implementation of every method, and the dispatch.
// A kind added to idl.json gains its typed arm here on regeneration; a hand arm
// overrides the table one by defining the same method on the hand set, which
// embeds the table set — so the arm set is total by construction, and the type
// checker refuses any hand set that is not.
func (g *gen) renderArms() []byte {
	tags := make([]string, len(g.idl.Kinds))
	for i, k := range g.idl.Kinds {
		tags[i] = k.Tag
	}
	sort.Strings(tags)
	var sb strings.Builder
	sb.WriteString(Header + "\n\n")
	sb.WriteString("package wire\n\nimport \"github.com/fuaran-ui/fuaran-go/wire/idl\"\n\n")
	sb.WriteString("// kindArms is the decoder arm set: exactly one method per kind idl.json declares.\n")
	sb.WriteString("type kindArms interface {\n")
	for _, t := range tags {
		fmt.Fprintf(&sb, "arm%s(w *walkState, obj map[string]any, path string) Obj\n", t)
	}
	sb.WriteString("}\n\n")
	sb.WriteString("// tableArms decodes every kind from its generated field table. The hand arm set\n")
	sb.WriteString("// embeds it, so a kind with no hand arm is still decoded field by field.\n")
	sb.WriteString("type tableArms struct{}\n\n")
	for _, t := range tags {
		fmt.Fprintf(&sb, "func (tableArms) arm%s(w *walkState, obj map[string]any, path string) Obj {\n", t)
		fmt.Fprintf(&sb, "return decodeKindByTable(w, obj, path, &idl.Kind%s)\n}\n\n", t)
	}
	sb.WriteString("// dispatchKindArm routes a discriminator already checked against the kind set.\n")
	sb.WriteString("func dispatchKindArm(a kindArms, w *walkState, tag string, obj map[string]any, path string) Obj {\n")
	sb.WriteString("switch tag {\n")
	for _, t := range tags {
		fmt.Fprintf(&sb, "case %q:\nreturn a.arm%s(w, obj, path)\n", t, t)
	}
	sb.WriteString("}\n")
	sb.WriteString("fail(CodeWrongNodeKind, path+\".$type\", \"unknown node kind '\"+tag+\"'\")\n")
	sb.WriteString("return Obj{}\n}\n")
	return []byte(sb.String())
}
